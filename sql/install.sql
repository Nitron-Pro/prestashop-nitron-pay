CREATE TABLE IF NOT EXISTS `PREFIX_nitron_pay_transaction` (
    `id_nitron_pay_transaction` INT(11) UNSIGNED NOT NULL AUTO_INCREMENT,
    `id_shop` INT(11) UNSIGNED NOT NULL DEFAULT 1,
    `id_cart` INT(11) UNSIGNED NOT NULL DEFAULT 0,
    `id_order` INT(11) UNSIGNED NOT NULL DEFAULT 0,
    `id_customer` INT(11) UNSIGNED NOT NULL DEFAULT 0,
    `uuid` VARCHAR(64) NULL DEFAULT NULL,
    `site_order_id` VARCHAR(64) NOT NULL,
    `gateway_name` VARCHAR(64) NULL DEFAULT NULL,
    `amount_rial` BIGINT(20) NOT NULL DEFAULT 0,
    `amount_order` DECIMAL(20, 6) NOT NULL DEFAULT 0.000000,
    `id_currency` INT(11) UNSIGNED NOT NULL DEFAULT 0,
    `status` VARCHAR(32) NOT NULL DEFAULT 'initiated',
    `ref_id` VARCHAR(64) NULL DEFAULT NULL,
    `card_pan` VARCHAR(32) NULL DEFAULT NULL,
    `payment_url` TEXT NULL DEFAULT NULL,
    `is_verified` TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
    `raw_create_response` LONGTEXT NULL DEFAULT NULL,
    `raw_verify_response` LONGTEXT NULL DEFAULT NULL,
    `date_add` DATETIME NOT NULL,
    `date_upd` DATETIME NOT NULL,
    PRIMARY KEY (`id_nitron_pay_transaction`),
    UNIQUE KEY `uniq_site_order_id` (`site_order_id`),
    KEY `idx_uuid` (`uuid`),
    KEY `idx_cart` (`id_cart`),
    KEY `idx_order` (`id_order`),
    KEY `idx_customer` (`id_customer`),
    KEY `idx_status` (`status`),
    KEY `idx_date_add` (`date_add`)
) ENGINE=ENGINE_TYPE DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `PREFIX_nitron_pay_log` (
    `id_nitron_pay_log` INT(11) UNSIGNED NOT NULL AUTO_INCREMENT,
    `id_shop` INT(11) UNSIGNED NOT NULL DEFAULT 1,
    `site_order_id` VARCHAR(64) NULL DEFAULT NULL,
    `uuid` VARCHAR(64) NULL DEFAULT NULL,
    `action` VARCHAR(64) NOT NULL,
    `request_payload` LONGTEXT NULL DEFAULT NULL,
    `response_payload` LONGTEXT NULL DEFAULT NULL,
    `status_code` INT(11) NULL DEFAULT NULL,
    `message` TEXT NULL DEFAULT NULL,
    `date_add` DATETIME NOT NULL,
    PRIMARY KEY (`id_nitron_pay_log`),
    KEY `idx_site_order_id` (`site_order_id`),
    KEY `idx_uuid` (`uuid`),
    KEY `idx_action` (`action`),
    KEY `idx_date_add` (`date_add`)
) ENGINE=ENGINE_TYPE DEFAULT CHARSET=utf8mb4;
